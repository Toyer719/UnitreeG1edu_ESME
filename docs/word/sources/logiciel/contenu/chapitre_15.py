def _cle(terme):
    t = terme[0].replace("œ", "oe").replace("Œ", "Oe")
    t = unicodedata.normalize("NFD", t).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9 ]", "", t)


TERMES.sort(key=_cle)

